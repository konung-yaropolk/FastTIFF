/// The same direction reversed: what an importer learned about a file has to
/// reach the document, or every measurement made on it afterwards is in the
/// wrong units.
#[test]
fn an_importers_metadata_reaches_the_document() {
    let mut raw = importer();
    let bytes: Vec<u8> = (0u16..16).flat_map(|v| v.to_le_bytes()).collect();
    let file = tmp("meta.raw", &bytes);

    let mut params = Params::new();
    params.set("width", ParamValue::Int(4));
    params.set("height", ParamValue::Int(4));
    params.set("type", ParamValue::Choice(1));
    params.set("pixel_size", ParamValue::Float(0.65));

    let result = raw
        .import(
            &ImportRequest {
                path: file.clone(),
                params,
            },
            &mut Silent,
        )
        .expect("import");

    let info = result.info.expect("the importer's metadata should cross");
    assert_eq!(info.spacing.x, Some(0.65));
    assert_eq!(info.spacing.y, Some(0.65));
    assert_eq!(info.unit.as_deref(), Some("micron"));
    assert!(
        info.description
            .as_deref()
            .unwrap_or("")
            .contains("raw import"),
        "{:?}",
        info.description
    );
    // The host fills these in, because it is the side that knows them.
    // The importer names it from the file stem, which tmp() prefixes.
    assert_eq!(info.name, "fasttiff-boundary-meta");
    assert_eq!(info.path.as_deref(), Some(file.to_string_lossy().as_ref()));

    // And it survives being turned into a real document.
    let s = plugins::to_stack(&result.image, Some(&info), false).expect("open");
    // Compared with a tolerance, not for equality: TIFF stores pixel size as
    // XResolution, a *rational*, so 0.65 goes to disk as 1/0.65 and comes back
    // as 0.6499999999999999. That is the file format, not the boundary — the
    // boundary is what the exact assertion on `info` above already checked.
    let close = |got: Option<f64>, want: f64| got.is_some_and(|v| (v - want).abs() < 1e-9);
    assert!(
        close(s.tiff.meta.pixel_width, 0.65) && close(s.tiff.meta.pixel_height, 0.65),
        "the spacing did not reach the written file: {:?} x {:?}",
        s.tiff.meta.pixel_width,
        s.tiff.meta.pixel_height
    );
    assert_eq!(s.tiff.meta.unit.as_deref(), Some("micron"));

    let _ = std::fs::remove_file(file);
}

/// An error from a plugin must read once, not twice. The plugin stores the
/// message and the host adds the framing; both doing it gave the user
/// "not applicable: not applicable: ...".
#[test]
fn an_error_is_framed_once_not_twice() {
    let mut raw = importer();
    let file = tmp("cancel.raw", &[0u8; 32]);

    struct Cancelled;
    impl ImportHost for Cancelled {
        fn progress(&mut self, _f: f32) -> bool {
            false
        }
        fn log(&mut self, _m: &str) {}
    }

    let mut params = Params::new();
    params.set("width", ParamValue::Int(4));
    params.set("height", ParamValue::Int(4));
    params.set("type", ParamValue::Choice(1));
    let err = raw
        .import(
            &ImportRequest {
                path: file.clone(),
                params,
            },
            &mut Cancelled,
        )
        .expect_err("a cancelled import must not succeed");

    // `Unsupported`'s Display prefix, exactly once.
    let msg = err.to_string();
    assert_eq!(msg, "not applicable: cancelled", "{msg}");
    assert_eq!(msg.matches("not applicable").count(), 1);

    let _ = std::fs::remove_file(file);
}

/// An importer's progress and log calls used to go nowhere: the host passed a
/// null table, so a long import could not be watched or stopped.
#[test]
fn an_importer_can_report_progress_and_be_stopped() {
    struct Watching {
        seen: Vec<f32>,
        logged: Vec<String>,
    }
    impl ImportHost for Watching {
        fn progress(&mut self, f: f32) -> bool {
            self.seen.push(f);
            true
        }
        fn log(&mut self, m: &str) {
            self.logged.push(m.to_string());
        }
    }

    let mut raw = importer();
    let bytes = vec![0u8; 4 * 4 * 2 * 3]; // three 4x4 u16 images
    let file = tmp("progress.raw", &bytes);

    let mut params = Params::new();
    params.set("width", ParamValue::Int(4));
    params.set("height", ParamValue::Int(4));
    params.set("type", ParamValue::Choice(1));
    params.set("images", ParamValue::Int(3));

    let mut host = Watching {
        seen: Vec::new(),
        logged: Vec::new(),
    };
    raw.import(
        &ImportRequest {
            path: file.clone(),
            params,
        },
        &mut host,
    )
    .expect("import");

    assert_eq!(
        host.seen,
        vec![0.0, 1.0 / 3.0, 2.0 / 3.0],
        "progress did not cross the boundary"
    );
    assert!(
        host.logged.iter().any(|m| m.contains("3 4x4")),
        "the importer's log did not cross: {:?}",
        host.logged
    );

    let _ = std::fs::remove_file(file);
}

