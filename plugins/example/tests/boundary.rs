/// The same direction reversed: what an importer learned about a file has to
/// reach the document, or every measurement made on it afterwards is in the
/// wrong units.
#[test]
fn an_importers_metadata_reaches_the_document() {
    let mut raw = importer();
    let bytes: Vec<u8> = (0u16..16).flat_map(|v| v.to_le_bytes()).collect();
    let file = tmp("meta.raw", &bytes);

    let mut params = Params::new();
    params.set("width", ParamValue::Int(4));
    params.set("height", ParamValue::Int(4));
    params.set("type", ParamValue::Choice(1));
    params.set("pixel_size", ParamValue::Float(0.65));

    let result = raw
        .import(
            &ImportRequest {
                path: file.clone(),
                params,
            },
            &mut Silent,
        )
        .expect("import");

    let info = result.info.expect("the importer's metadata should cross");
    assert_eq!(info.spacing.x, Some(0.65));
    assert_eq!(info.spacing.y, Some(0.65));
    assert_eq!(info.unit.as_deref(), Some("micron"));
    assert!(
        info.description
            .as_deref()
            .unwrap_or("")
            .contains("raw import"),
        "{:?}",
        info.description
    );
    // The host fills these in, because it is the side that knows them.
    // The importer names it from the file stem, which tmp() prefixes.
    assert_eq!(info.name, "fasttiff-boundary-meta");
    assert_eq!(info.path.as_deref(), Some(file.to_string_lossy().as_ref()));

    // And it survives being turned into a real document.
    let s = plugins::to_stack(&result.image, Some(&info), false).expect("open");
    // Compared with a tolerance, not for equality: TIFF stores pixel size as
    // XResolution, a *rational*, so 0.65 goes to disk as 1/0.65 and comes back
    // as 0.6499999999999999. That is the file format, not the boundary — the
    // boundary is what the exact assertion on `info` above already checked.
    let close = |got: Option<f64>, want: f64| got.is_some_and(|v| (v - want).abs() < 1e-9);
    assert!(
        close(s.tiff.meta.pixel_width, 0.65) && close(s.tiff.meta.pixel_height, 0.65),
        "the spacing did not reach the written file: {:?} x {:?}",
        s.tiff.meta.pixel_width,
        s.tiff.meta.pixel_height
    );
    assert_eq!(s.tiff.meta.unit.as_deref(), Some("micron"));

    let _ = std::fs::remove_file(file);
}

/// An error from a plugin must read once, not twice. The plugin stores the
/// message and the host adds the framing; both doing it gave the user
/// "not applicable: not applicable: ...".
#[test]
fn an_error_is_framed_once_not_twice() {
    let mut raw = importer();
    let file = tmp("cancel.raw", &[0u8; 32]);

    struct Cancelled;
    impl ImportHost for Cancelled {
        fn progress(&mut self, _f: f32) -> bool {
            false
        }
        fn log(&mut self, _m: &str) {}
    }

    let mut params = Params::new();
    params.set("width", ParamValue::Int(4));
    params.set("height", ParamValue::Int(4));
    params.set("type", ParamValue::Choice(1));
    let err = raw
        .import(
            &ImportRequest {
                path: file.clone(),
                params,
            },
            &mut Cancelled,
        )
        .expect_err("a cancelled import must not succeed");

    // `Unsupported`'s Display prefix, exactly once.
    let msg = err.to_string();
    assert_eq!(msg, "not applicable: cancelled", "{msg}");
    assert_eq!(msg.matches("not applicable").count(), 1);

    let _ = std::fs::remove_file(file);
}

/// An importer's progress and log calls used to go nowhere: the host passed a
/// null table, so a long import could not be watched or stopped.
#[test]
fn an_importer_can_report_progress_and_be_stopped() {
    struct Watching {
        seen: Vec<f32>,
        logged: Vec<String>,
    }
    impl ImportHost for Watching {
        fn progress(&mut self, f: f32) -> bool {
            self.seen.push(f);
            true
        }
        fn log(&mut self, m: &str) {
            self.logged.push(m.to_string());
        }
    }

    let mut raw = importer();
    let bytes = vec![0u8; 4 * 4 * 2 * 3]; // three 4x4 u16 images
    let file = tmp("progress.raw", &bytes);

    let mut params = Params::new();
    params.set("width", ParamValue::Int(4));
    params.set("height", ParamValue::Int(4));
    params.set("type", ParamValue::Choice(1));
    params.set("images", ParamValue::Int(3));

    let mut host = Watching {
        seen: Vec::new(),
        logged: Vec::new(),
    };
    raw.import(
        &ImportRequest {
            path: file.clone(),
            params,
        },
        &mut host,
    )
    .expect("import");

    assert_eq!(
        host.seen,
        vec![0.0, 1.0 / 3.0, 2.0 / 3.0],
        "progress did not cross the boundary"
    );
    assert!(
        host.logged.iter().any(|m| m.contains("3 4x4")),
        "the importer's log did not cross: {:?}",
        host.logged
    );

    let _ = std::fs::remove_file(file);
}

// ------------------------------------------------------- the `dlopen` lane

/// Where the example library lands, derived from this test binary's own path so
/// that debug and release both work without being told which.
///
/// `None` when it has not been built, or when it is older than its source:
/// `cargo test` does not rebuild a `cdylib`, and a smoke test that silently
/// exercised last week's binary would be worse than no smoke test.
fn built_library() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    // .../target/<profile>/deps/plugin_library-<hash>.exe
    let path = exe.parent()?.parent()?.join(format!(
        "{}fasttiff_plugin_example.{}",
        if cfg!(target_os = "windows") {
            ""
        } else {
            "lib"
        },
        plugins::LIBRARY_EXT
    ));
    let built = std::fs::metadata(&path).ok()?.modified().ok()?;

    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/lib.rs");
    let edited = std::fs::metadata(src).ok()?.modified().ok()?;
    (built >= edited).then_some(path)
}

/// `dlopen` + `dlsym` + everything above: the one thing `register_from` cannot
/// cover. Skips rather than fails, because whether the artifact exists depends
/// on how cargo was invoked, not on whether the code is right.
#[test]
fn a_built_shared_library_loads_and_registers() {
    let Some(path) = built_library() else {
        eprintln!(
            "skipping the dlopen smoke test: no current \
             fasttiff_plugin_example.{} (run `cargo build -p fasttiff-plugin-example`)",
            plugins::LIBRARY_EXT
        );
        return;
    };
    let loaded = library::load_library(&path)
        .unwrap_or_else(|e| panic!("{} should load: {e}", path.display()));
    assert_eq!(loaded.plugins.len(), 4);
    assert_eq!(loaded.importers.len(), 1);
    assert_eq!(loaded.plugins[0].info().id, "dev.fasttiff.example.invert");
}

/// The path a user actually takes: put a library in the plugin folder, start
/// the app, and find it in the menu.
///
/// Everything above tests a plugin the test handed to the loader itself. This
/// tests *discovery* — the search path, the extension filter, and
/// `Registry::with_installed` — which is the half that was broken the first
/// time this feature was tried.
///
/// It sets `FASTTIFF_PLUGIN_PATH`, which is process-global. Safe here only
/// because no other test in this binary reads it; do not add one that does.
#[test]
fn a_library_in_the_plugin_folder_reaches_the_menu() {
    let Some(built) = built_library() else {
        eprintln!("skipping discovery test: no current example library");
        return;
    };

    let dir = std::env::temp_dir().join("fasttiff-plugin-discovery-test");
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("create plugin dir");
    let installed = dir.join(built.file_name().expect("file name"));
    std::fs::copy(&built, &installed).expect("copy the library");
    // A file with the right extension that is not a library, and one with the
    // wrong extension: the scan must report the first and ignore the second.
    std::fs::write(
        dir.join(format!("broken.{}", plugins::LIBRARY_EXT)),
        b"junk",
    )
    .unwrap();
    std::fs::write(dir.join("notes.txt"), b"not a plugin").unwrap();

    std::env::set_var(plugins::discover::PLUGIN_PATH_VAR, &dir);
    assert!(
        plugins::search_paths().contains(&dir),
        "the override should come first on the search path"
    );

    let reg = Registry::with_installed();
    std::env::remove_var(plugins::discover::PLUGIN_PATH_VAR);

    assert!(
        reg.find("dev.fasttiff.example.invert").is_some(),
        "a library in the plugin folder should reach the menu; problems: {:?}",
        reg.problems
    );
    assert!(
        reg.claims_extension(Path::new("scan.raw")),
        "its importer should reach the Open dialog"
    );
    // The junk file is reported, by name, rather than silently skipped.
    assert!(
        reg.problems.iter().any(|p| p.contains("broken.")),
        "the unloadable file should be reported: {:?}",
        reg.problems
    );
    assert!(
        !reg.problems.iter().any(|p| p.contains("notes.txt")),
        "a non-library must not be treated as a failed plugin: {:?}",
        reg.problems
    );

    let _ = std::fs::remove_dir_all(&dir);
}

/// Loading something that is not a plugin must be a message, not a crash.
#[test]
fn a_file_that_is_not_a_plugin_is_reported_rather_than_loaded() {
    let junk = tmp(&format!("junk.{}", plugins::LIBRARY_EXT), b"not a library");
    let err = library::load_library(&junk).expect_err("junk must not load");
    assert!(
        err.contains("could not load") || err.contains("ft_plugin_v1_query"),
        "unhelpful message: {err}"
    );
    let _ = std::fs::remove_file(junk);
}

/// A real, loadable shared library with no plugin entry point — which is what
/// lands in the plugin folder by accident — must be turned away by the missing
/// symbol rather than by failing to load.
///
/// The platform's own C library, because it is the one shared library that is
/// certainly present, certainly loadable, and certainly not a plugin.
///
/// Not this test binary, which was the obvious choice and the wrong one: it
/// links the example plugin, so it *defines* `ft_plugin_v1_query`. Windows and
/// Linux do not put an executable's symbols where `dlopen` can reach them and
/// the test passed by accident; macOS does, and it loaded — correctly, since
/// on that platform the binary really is a plugin.
#[test]
fn a_real_binary_without_the_entry_point_is_rejected_by_symbol() {
    // Loaded by name so the platform's own loader resolves it.
    let libc = if cfg!(windows) {
        "kernel32.dll"
    } else if cfg!(target_os = "macos") {
        "libSystem.B.dylib"
    } else {
        "libc.so.6"
    };
    match library::load_library(Path::new(libc)) {
        Ok(_) => panic!("{libc} is not a plugin and must not load as one"),
        Err(e) => assert!(
            // Either rejection is the promise being kept: a reason rather than
            // a crash. Which one depends on whether this system has that
            // library under that name — a musl container has no `libc.so.6`,
            // and then the point is only that the refusal says so.
            e.contains("could not load") || e.contains("ft_plugin_v1_query"),
            "unhelpful message: {e}"
        ),
    }
}

// ------------------------------------------------------------------- plots
//
// The one result that crosses in both directions: the chart comes back through
// the sink, and the regions it is a chart *of* go the other way through the
// host table. Before ABI 1.2 neither half existed — a `.dll` plugin returning a
// plot was refused outright, and had it not been, it would have seen an empty
// selection for ever and silently re-measured the whole frame each time the
// user drew something.

/// The fixture's sample at plane `t`, pixel index `i`. Stated here rather than
/// read back out of the stack, so the expected means are arithmetic this test
/// did itself instead of a second copy of the code under test.
fn fixture_sample(t: usize, i: usize) -> f64 {
    (t * 10) as f64 + i as f64 * 0.5
}

/// The mean over `indices` at plane `t`, as `f32` — the same width the plugin
/// reports in.
fn expected_mean(t: usize, indices: &[usize]) -> f32 {
    let sum: f64 = indices.iter().map(|&i| fixture_sample(t, i)).sum();
    (sum / indices.len() as f64) as f32
}

fn run_plot(s: &fast_tiff_viewer::stack::Stack, rois: Vec<Roi>) -> fasttiff_plugin_api::Plot {
    let mut from_library = plugin("dev.fasttiff.example.plotmean");
    let view = plugins::describe_view(s, 0, false, volume());
    let mut host = plugins::StackHost::new(s, view).with_selection(rois);
    match from_library.run(&mut host, &Params::new()) {
        Ok(Outcome::Plot(p)) => *p,
        other => panic!("expected a plot, got {other:?}"),
    }
}

/// With nothing drawn, the plugin measures the whole frame — and every field of
/// the chart survives the crossing.
#[test]
fn a_plot_crosses_a_real_library_boundary() {
    let frames = 4;
    let s = stack(1, frames);
    let plot = run_plot(&s, Vec::new());

    assert_eq!(plot.title, "Mean over time");
    assert_eq!(plot.y_label, "Mean value");
    // No frame interval in the fixture, so the axis is frame numbers and says
    // so, rather than seconds computed from an interval nobody stated.
    assert_eq!(plot.x_label, "T (frames)");
    assert_eq!((plot.x_start, plot.x_step), (0.0, 1.0));
    // Without this the host arms no tool, the user can draw nothing, and the
    // plugin is never called again — a plot that silently cannot be narrowed.
    assert_eq!(plot.wants, SelectionKind::Regions);

    assert_eq!(plot.series.len(), 1);
    assert_eq!(plot.series[0].label, "Whole frame");
    assert_eq!(plot.series[0].color, None);
    let all: Vec<usize> = (0..20).collect();
    let want: Vec<f32> = (0..frames).map(|t| expected_mean(t, &all)).collect();
    assert_eq!(plot.series[0].values, want);
    // Not vacuous: the trace has to actually go somewhere.
    assert!(want[0] != want[frames - 1]);
}

/// The regions the user drew reach a plugin on the other side of the boundary,
/// and each one gets its own trace.
#[test]
fn the_regions_the_user_drew_reach_a_library_plugin() {
    let frames = 3;
    let s = stack(1, frames);
    // The fixture is 5x4. Two regions that share no pixel, so a swap or a
    // dropped offset cannot land on the same numbers.
    let a = Roi {
        shape: Shape::Rect,
        x: 0,
        y: 0,
        w: 2,
        h: 2,
    };
    let b = Roi {
        shape: Shape::Rect,
        x: 3,
        y: 2,
        w: 2,
        h: 2,
    };
    let plot = run_plot(&s, vec![a, b]);

    assert_eq!(plot.series.len(), 2, "one trace per region");
    assert_eq!(plot.series[0].label, "Region 1");
    assert_eq!(plot.series[1].label, "Region 2");
    for (series, roi) in plot.series.iter().zip([a, b]) {
        let idx = roi.indices(5, 4);
        let want: Vec<f32> = (0..frames).map(|t| expected_mean(t, &idx)).collect();
        assert_eq!(series.values, want, "for {roi:?}");
    }
    // The two regions must genuinely disagree, or the test would pass with the
    // geometry ignored entirely.
    assert!(plot.series[0].values[0] != plot.series[1].values[0]);
}

/// An ellipse crosses as an ellipse.
///
/// The shape is one `u32` in the middle of the region, and dropping it is
/// invisible: the plugin would measure the bounding box instead, over the right
/// frames, in the right units, and produce a trace that looks completely
/// ordinary and is averaged over the wrong pixels.
///
/// This one needs its own fixture. The stack every other test uses rises
/// linearly with the pixel index, and a rectangle and the ellipse inscribed in
/// it are both symmetric about the same centre — so over a straight ramp their
/// means are *equal*, and the test would pass with the shape thrown away. The
/// field here is the square of the index, under which a symmetric set no longer
/// averages to its centre.
#[test]
fn an_ellipse_crosses_as_an_ellipse() {
    let (w, h) = (5u32, 4u32);
    let n = (w * h) as usize;
    let curved = |t: usize, i: usize| (t * 400 + i * i) as f64;
    let img = ImageResult {
        width: w,
        height: h,
        channels: 1,
        slices: 1,
        frames: 2,
        pixel_type: PixelType::F32,
        planes: (0..2)
            .map(|t| PlaneData::F32((0..n).map(|i| curved(t, i) as f32).collect()))
            .collect(),
        channel_colors: Vec::new(),
        metadata: None,
        name: "curved".into(),
    };
    let s = plugins::to_stack(&img, None, false).expect("the fixture should open");
    let mean = |t: usize, idx: &[usize]| -> f32 {
        (idx.iter().map(|&i| curved(t, i)).sum::<f64>() / idx.len() as f64) as f32
    };

    let rect = Roi {
        shape: Shape::Rect,
        x: 0,
        y: 0,
        w: 4,
        h: 4,
    };
    let ellipse = rect.with_shape(Shape::Ellipse);
    let (ri, ei) = (rect.indices(w, h), ellipse.indices(w, h));

    // The premise, asserted rather than assumed: if the two shapes agreed here
    // the rest of this test would prove nothing at all.
    assert!(ei.len() < ri.len(), "the ellipse must be the smaller set");
    assert!(
        mean(0, &ri) != mean(0, &ei),
        "the fixture must tell the two shapes apart"
    );

    let plot = run_plot(&s, vec![ellipse]);
    assert_eq!(plot.series[0].values[0], mean(0, &ei));
    assert!(
        plot.series[0].values[0] != mean(0, &ri),
        "the shape was dropped and the bounding box measured instead"
    );
}

/// A stated frame interval makes the axis seconds, and the interval itself
/// crosses as the x step.
///
/// Worth its own case because the step is `1.0` by default: a plugin whose
/// scale never crossed would produce a correct-looking chart on every file that
