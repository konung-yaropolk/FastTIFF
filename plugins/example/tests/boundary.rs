/// The registry must not be able to tell where a plugin came from, except
/// through `Origin` — which is the whole design goal of the loader.
#[test]
fn loaded_plugins_join_the_same_registry_as_the_built_ins() {
    let loaded = example();

    let mut reg = Registry::new();
    let built_ins = reg.len();
    for p in loaded.plugins {
        assert!(reg.add(Box::new(p), Origin::Library));
    }
    for i in loaded.importers {
        assert!(reg.add_importer(Box::new(i), Origin::Library));
    }
    assert_eq!(reg.len(), built_ins + 3);
    assert!(
        reg.problems.is_empty(),
        "the example plugin should install cleanly: {:?}",
        reg.problems
    );

    let i = reg
        .find("dev.fasttiff.example.invert")
        .expect("the loaded plugin should be findable by id");
    assert_eq!(reg.entries()[i].origin, Origin::Library);

    // The Open dialog picks up the plugin's extensions.
    let types = reg.open_file_types();
    assert!(
        types
            .iter()
            .any(|t| t.extensions.contains(&"raw".to_string())),
        "the plugin's file type did not reach the Open dialog: {types:?}"
    );
    assert!(reg.claims_extension(Path::new("a.bin")));
}

/// Pixels read through the C boundary must be the same pixels, not merely
/// similar ones — the host-callback direction, which the oracle covers only
/// indirectly.
#[test]
fn planes_read_by_a_loaded_plugin_address_the_same_data_as_the_host() {
    let mut from_library = plugin("dev.fasttiff.example.invert");

    let s = stack(3, 2);
    // Frame 1, so a plugin that ignored `frame_index` and read frame 0 fails.
    let view = plugins::describe_view(&s, 1, false, volume());
    let mut host = plugins::StackHost::new(&s, view);

    let mut params = Params::new();
    params.set("all_channels", ParamValue::Bool(true));
    let Outcome::NewDocument(got) = from_library.run(&mut host, &params).expect("run") else {
        panic!("expected a document");
    };

    let mut host = plugins::StackHost::new(&s, plugins::describe_view(&s, 1, false, volume()));
    let mut buf = Vec::new();
    for c in 0..3 {
        host.read_plane_f32(Plane::new(c, 0, 1), &mut buf)
            .expect("read");
        let lo = buf.iter().cloned().fold(f32::INFINITY, f32::min);
        let hi = buf.iter().cloned().fold(f32::NEG_INFINITY, f32::max);
        let want: Vec<f32> = buf.iter().map(|&v| hi - (v - lo)).collect();
        assert_eq!(
            got.planes[c],
            PlaneData::F32(want),
            "channel {c} of frame 1 came back computed from different pixels"
        );
    }
}

/// The guarantee everything else rests on: a plugin that genuinely panics must
/// come back as an error, and the process must still be running to read it.
///
/// This is the only test that fires a real panic through the boundary. The host
/// cannot catch it — an `extern "C"` function aborts on unwind — so what is
/// under test is `export_plugin!`'s own guard, and the only way to test that is
/// to let a plugin built with the macro actually panic.
#[test]
fn a_plugin_that_really_panics_is_contained_and_reported() {
    let mut panics = plugin("dev.fasttiff.example.panics");

    let s = stack(1, 1);
    for choice in [0usize, 1] {
        let mut params = Params::new();
        params.set("where", ParamValue::Choice(choice));
        let mut host = plugins::StackHost::new(&s, plugins::describe_view(&s, 0, false, volume()));
        let err = panics
            .run(&mut host, &params)
            .expect_err("a panicking plugin must be an error, not a result");
        assert!(
            err.to_string().contains("panicked"),
            "the panic must be reported as one: {err}"
        );
        assert!(
            err.to_string().contains("on purpose"),
            "the plugin's own panic message should reach the user: {err}"
        );
    }

    // Still alive, and still able to run something else.
    let mut invert = plugin("dev.fasttiff.example.invert");
    let mut host = plugins::StackHost::new(&s, plugins::describe_view(&s, 0, false, volume()));
    assert!(
        matches!(
            invert.run(&mut host, &Params::new()),
            Ok(Outcome::NewDocument(_))
        ),
        "a panic in one plugin must not poison another"
    );
}

/// The metadata half of the boundary. Pixels crossing proves nothing about
/// whether the file's *scale* crossed, and a plugin that silently measures in
/// pixels while believing it is measuring in microns is worse than one that
/// fails.
#[test]
fn the_files_calibration_reaches_a_loaded_plugin() {
    let mut show = plugin("dev.fasttiff.example.showinfo");

    // A stack carrying every optional field, so a dropped one is visible.
    let s = stack(2, 1);
    let mut info = plugins::describe_stack(&s);
    info.unit = Some("micron".into());
    info.spacing = fasttiff_plugin_api::Spacing {
        x: Some(0.325),
        y: Some(0.325),
        z: Some(1.5),
    };
    info.frame_interval_s = Some(0.05);
    info.calibration = Some((-100.0, 2.5));
    info.channel_names = vec!["GFP".into(), "mCherry".into()];
    info.description = Some("ImageJ=1.54f\nunit=micron".into());
    info.mode = fasttiff_plugin_api::DisplayMode::Composite;

    let view = plugins::describe_view(&s, 0, false, volume());
    let mut host = plugins::StackHost::new(&s, view).with_info(info.clone());

    let Outcome::Message(report) = show.run(&mut host, &Params::new()).expect("run") else {
        panic!("Show Info should report a message");
    };

    // Each of these is `unknown`/`none` unless the value really crossed.
    assert!(report.contains("pixel: 0.325 x 0.325 micron"), "{report}");
    assert!(report.contains("z step: 1.5 micron"), "{report}");
    assert!(report.contains("frame interval: 0.05 s"), "{report}");
    assert!(report.contains("calibration: -100 + 2.5 * raw"), "{report}");
    assert!(report.contains("channels: GFP, mCherry"), "{report}");
    assert!(report.contains("mode: Composite"), "{report}");
    assert!(report.contains("description: 24 bytes"), "{report}");
    assert!(report.contains("2 channel(s)"), "{report}");

    // And the log line crossed too.
    assert!(
        host.messages.iter().any(|m| m.contains("metadata")),
        "the plugin's log line did not reach the host: {:?}",
        host.messages
    );
}

