//! The C boundary, end to end, through a real third-party plugin.
//!
//! Everything else about plugins is tested against types compiled into the test
//! binary and reached through a Rust trait object, where the boundary does not
//! exist. These tests go through `fasttiff-plugin-example`'s `extern "C"` entry
//! point and its function-pointer vtables, so they are the only ones that can
//! catch a mismatch between the two sides of the ABI — a reordered struct
//! field, a marshalling step that drops a value, a plane index computed
//! differently on each side.
//!
//! The oracle is exact. The example library's `Invert` is a copy of the
//! viewer's built-in `Invert`, so running both over the same stack must produce
//! *identical* results, down to the float bits and the result's name. A
//! comparison with no tolerance is only possible because the boundary is meant
//! to be lossless, which is the property worth pinning.
//!
//! # Why this lives in the plugin's crate, and why not `dlopen`
//!
//! Because `cargo test` does not build a `cdylib`. A test that could only reach
//! the plugin by loading a `.dll` would either skip (if nobody had run
//! `cargo build` first) or — far worse — pass against a **stale** artifact
//! built from different source, which is exactly what happened while these
//! tests were being written: a deliberately broken plugin kept the oracle
//! green. So the marshalling is tested through `library::register_from`, which
//! is the whole loader minus `dlopen`/`dlsym`, called with the query function
//! of a plugin cargo has *just rebuilt* — guaranteed, because that plugin is
//! this crate. `dlopen` itself gets a smoke test at the bottom, which skips
//! when the artifact is missing or older than its source; there is nothing in
//! those two library calls worth a false green.

#![cfg(not(target_arch = "wasm32"))]

use fast_tiff_viewer::plugins::{self, library, Origin, Registry};
use fasttiff_plugin_api::{
    Confidence, ExportRequest, Exporter, HostContext, ImageResult, ImportHost, ImportRequest,
    Importer, Outcome, ParamKind, ParamValue, Params, PixelType, Plane, PlaneData, Plugin, Roi,
    SelectionKind, Shape, StackInfo, VolumeMode, VolumeView,
};
use std::path::{Path, PathBuf};

/// Load the example plugin through the ABI, without a shared library.
///
/// `ft_plugin_v1_query` is the same `#[no_mangle] extern "C"` function the
/// `.dll` exports; reaching it as a Rust path rather than through `dlsym`
/// changes how it is *found*, not how it is *called*.
fn example() -> library::Loaded {
    // SAFETY: the symbol is generated by `export_plugin!`, so it has exactly
    // the signature `FtQueryFn` names, and it is linked into this binary for
    // the whole run.
    unsafe {
        library::register_from(
            fasttiff_plugin_example::ft_plugin_v1_query,
            Path::new("fasttiff-plugin-example"),
        )
    }
    .expect("the example plugin should register")
}

/// One registered plugin, by id.
fn plugin(id: &str) -> library::LoadedPlugin {
    example()
        .plugins
        .into_iter()
        .find(|p| p.info().id == id)
        .unwrap_or_else(|| panic!("{id} should be registered"))
}

/// The registered importer.
fn importer() -> library::LoadedImporter {
    example().importers.remove(0)
}

/// The registered exporter.
fn exporter() -> library::LoadedExporter {
    example().exporters.remove(0)
}

fn volume() -> VolumeView {
    VolumeView {
        mode: VolumeMode::Mip,
        density: 1.0,
        iso: 0.5,
        eye: [0.0; 3],
        forward: [0.0, 0.0, 1.0],
        up: [0.0, 1.0, 0.0],
        right: [1.0, 0.0, 0.0],
    }
}

/// A small float stack whose planes are all different, so a mixed-up plane
/// index cannot pass unnoticed.
fn stack(channels: usize, frames: usize) -> fast_tiff_viewer::stack::Stack {
    let (w, h) = (5u32, 4u32);
    let n = (w * h) as usize;
    let mut planes = Vec::new();
    for t in 0..frames {
        for c in 0..channels {
            let base = (c * 1000 + t * 10) as f32;
            planes.push(PlaneData::F32(
                (0..n).map(|i| base + i as f32 * 0.5).collect(),
            ));
        }
    }
    let img = ImageResult {
        width: w,
        height: h,
        channels,
        slices: 1,
        frames,
        pixel_type: PixelType::F32,
        planes,
        channel_colors: Vec::new(),
        metadata: None,
        name: "oracle".into(),
    };
    plugins::to_stack(&img, None, false).expect("the fixture should open")
}

#[test]
fn the_library_registers_what_it_declares() {
    let loaded = example();

    let ids: Vec<String> = loaded.plugins.iter().map(|p| p.info().id.clone()).collect();
    assert_eq!(
        ids,
        vec![
            "dev.fasttiff.example.invert",
            "dev.fasttiff.example.showinfo",
            "dev.fasttiff.example.plotmean",
            "dev.fasttiff.example.panics"
        ],
        "both plugins must register, in the order the macro lists them"
    );

    let importers: Vec<String> = loaded
        .importers
        .iter()
        .map(|i| i.info().id.clone())
        .collect();
    assert_eq!(importers, vec!["dev.fasttiff.example.raw"]);

    let exporters: Vec<String> = loaded
        .exporters
        .iter()
        .map(|e| e.info().id.clone())
        .collect();
    assert_eq!(exporters, vec!["dev.fasttiff.example.csv"]);

    // Strings really crossed, rather than arriving empty or as the id again.
    let info = loaded.plugins[0].info();
    assert_eq!(info.name, "Invert (from library)");
    assert_eq!(info.menu_path, "Examples");
    assert!(!info.version.is_empty(), "the version did not cross");
    assert!(
        info.description.contains("shared library"),
        "the description did not cross: {:?}",
        info.description
    );

    // And the importer's file types, which the Open dialog is built from.
    let types = loaded.importers[0].file_types();
    assert_eq!(types.len(), 1);
    assert_eq!(types[0].description, "Raw binary image");
    assert_eq!(types[0].extensions, vec!["raw", "bin"]);

    // And the exporter's, which the Save-as dialog is built from. They travel
    // through the same descriptor field as an importer's, so this is only worth
    // asserting because the two arrive by different callbacks.
    let types = loaded.exporters[0].file_types();
    assert_eq!(types.len(), 1);
    assert_eq!(types[0].description, "Comma-separated values");
    assert_eq!(types[0].extensions, vec!["csv"]);
}

/// The point of the whole phase: the same filter, one side called as a Rust
/// trait and one side through the C vtable, must agree exactly.
#[test]
fn a_loaded_plugin_matches_the_built_in_it_was_copied_from() {
    let mut from_library = plugin("dev.fasttiff.example.invert");
    let mut built_in = plugins::builtin::Invert;

    for (channels, frames, all) in [(1usize, 1usize, false), (3, 2, true), (3, 2, false)] {
        let s = stack(channels, frames);
        let mut params = Params::new();
        params.set("all_channels", ParamValue::Bool(all));

        let view = plugins::describe_view(&s, frames - 1, false, volume());
        let mut host = plugins::StackHost::new(&s, view.clone());
        let want = built_in.run(&mut host, &params).expect("built-in run");

        let mut host = plugins::StackHost::new(&s, view);
        let got = from_library.run(&mut host, &params).expect("library run");

        let (Outcome::NewDocument(want), Outcome::NewDocument(got)) = (&want, &got) else {
            panic!("both should produce a document, got {want:?} / {got:?}");
        };
        assert_eq!(
            got, want,
            "the library's result differs from the built-in's for \
             {channels}c x {frames}t, all_channels={all}"
        );
        // Not vacuous: the fixture must actually have produced pixels, and the
        // `all_channels` flag must have crossed and been acted on.
        assert_eq!(want.planes.len(), if all { channels } else { 1 });
        assert_eq!(want.planes[0].len(), 20);
    }
}

